/**
 * Write a whole file.
 *
 * @ingroup developer
 */
static void write_file(const std::string_view& contents,
    const std::filesystem::path& dst) {
  if (dst.has_parent_path()) {
    std::filesystem::create_directories(dst.parent_path());
  }
  std::fstream out(dst, std::ios::out);
  if (!out.is_open()) {
    throw std::runtime_error("could not write file " + dst.string());
  }
  out << contents;
}

void write_file_prompt(const std::string_view& contents,
    const std::filesystem::path& dst) {
  if (dst.has_parent_path()) {
    std::filesystem::create_directories(dst.parent_path());
  }
  if (std::filesystem::exists(dst)) {
    std::cout << dst.string() << " already exists, overwrite? [y/N] ";
    std::string ans;
    std::getline(std::cin, ans);
    if (ans.length() > 0 && (ans[0] == 'y' || ans[0] == 'Y')) {
      write_file(contents, dst);
    }
  } else {
    write_file(contents, dst);
  }
}

std::string gulp(const std::filesystem::path& src) {
  std::string contents;
  std::ifstream in(src);
  if (!in.is_open()) {
    throw std::runtime_error("could not read file " + src.string());
  }
  char buffer[8192];
  while (in.read(buffer, sizeof(buffer))) {
    contents.append(buffer, sizeof(buffer));
  }
  contents.append(buffer, in.gcount());
  return contents;
}

bool can_write(const std::filesystem::path& path) {
  bool canWrite = true;
  if (std::filesystem::exists(path)) {
    try {
      YAMLParser parser;
      YAMLNode node = parser.parse(path.native());
      canWrite = node.isValue("generator") && node.value("generator") == "doxide";
    } catch (const std::runtime_error& e) {
      warn(e.what());
      canWrite = false;
    }
  }
  if (!canWrite) {
    warn(std::filesystem::absolute(path).native() << " already exists and was not generated by doxide, will not overwrite");
  }
  return canWrite;
}
